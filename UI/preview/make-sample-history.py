"""Builds preview/sample-history.js from a captures.csv (ModsData/LiveTrafficRouting), so the panel preview shows
real runs in Compare / History / Runs. Same JSON keys as TrafficCapture.AppendJson and TrafficReportStore.RunsJson.

    python make-sample-history.py <path to captures.csv>
"""
import csv
import json
import os
import sys

KEYS = {  # JSON key -> CSV column
    "veh": "vehicles", "speed": "avg_speed_pct", "queued": "queued_pct", "local": "local_street_pct",
    "jams": "jam_warnings", "jamsMax": "jam_warnings_max", "flow": "flow_pct", "navKmh": "nav_progress_kmh",
    "otherKmh": "other_progress_kmh", "navShare": "nav_share_pct", "rr": "reroutes", "rrCars": "reroute_cars",
    "rrTrucks": "reroute_trucks", "rrTaxis": "reroute_taxis", "rrBetter": "reroute_better", "rrNoBetter": "reroute_no_better",
    "rrSaved": "reroute_saved_pct", "rrHeld": "reroute_held_back", "planSpeed": "planner_speed_pct",
    "planJammed": "planner_jammed_pct", "ms": "mod_ms", "planFc": "planner_forecast_pct", "planLocal": "planner_local_pct",
    "fcMaxVc": "forecast_max_vc", "fcVeh": "forecast_vehicles", "rrEmerg": "reroute_emergency", "rrDefer": "reroute_deferred",
    "rrBudget": "reroute_budget", "carPax": "car_passengers", "transitPax": "transit_passengers", "transit": "transit_share_pct",
    "dsStuck": "despawn_stuck", "dsFailed": "despawn_failed", "rmDone": "removed_done", "rrFailed": "reroute_failed",
    "rrGone": "reroute_gone", "rrJam": "reroute_jam", "rrJamEval": "reroute_jam_evaluated", "rrJamBetter": "reroute_jam_better",
    "rrAtJunction": "reroute_at_junction", "cCom": "car_commute_pct", "cHome": "car_home_pct", "cShop": "car_shop_pct",
    "cLeis": "car_leisure_pct", "cOth": "car_other_pct", "qCom": "queued_commute_pct", "qHome": "queued_home_pct",
    "qShop": "queued_shop_pct", "qLeis": "queued_leisure_pct", "qOth": "queued_other_pct", "sTrips": "shop_trips",
    "sPlaces": "shop_places", "sTop5": "shop_top5_pct", "sKm": "shop_km", "lTrips": "leisure_trips",
    "lPlaces": "leisure_places", "lTop5": "leisure_top5_pct", "lKm": "leisure_km", "spd": "speed_setting",
    "simFps": "sim_fps", "fps": "render_fps", "cpu": "mod_cpu_pct", "modMb": "mod_mem_mb", "gameMb": "game_mem_mb",
    "bikePax": "bike_riders", "walking": "walking", "waitTransit": "waiting_transit", "waitRoute": "waiting_route",
    "carShare": "car_share_pct",
    "h": "game_hour", "n": "samples",
}


def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return -1


rows = list(csv.DictReader(open(sys.argv[1], encoding="utf-8-sig")))
history = []
for r in rows:
    c = {"t": r["game_time"], "run": r["run_id"], "mode": r["mode"], "preset": r["preset"], "auto": r.get("auto_setup", "")}
    for key, col in KEYS.items():
        c[key] = num(r.get(col))
    history.append(c)

runs = []
for run_id in dict.fromkeys(r["run_id"] for r in rows):
    rs = [r for r in rows if r["run_id"] == run_id]
    runs.append({"id": run_id, "mode": rs[0]["mode"], "preset": rs[0]["preset"], "settings": rs[0]["settings"],
                 "first": rs[0]["game_time"], "last": rs[-1]["game_time"], "hours": len(rs), "pinned": 0,
                 "baseline": 1 if rs[0]["mode"] == "Native" else 0})

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "sample-history.js")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by make-sample-history.py from a real captures.csv (preview only).\n")
    f.write("window.__previewData = window.__previewData || {};\n")
    f.write("window.__previewData.history = %s;\n" % json.dumps(json.dumps(history)))
    f.write("window.__previewData.runs = %s;\n" % json.dumps(json.dumps(runs)))
print("wrote", out, len(history), "hours,", len(runs), "runs")
